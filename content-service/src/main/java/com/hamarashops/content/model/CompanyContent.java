package com.hamarashops.content.model;

public class CompanyContent {
    private String name;
    private String headline;
    private String mission;
    private String vision;
    private String approach;
    private String journey;

    public CompanyContent() {}

    public String getName() { return name; }
    public void setName(String name) { this.name = name; }

    public String getHeadline() { return headline; }
    public void setHeadline(String headline) { this.headline = headline; }

    public String getMission() { return mission; }
    public void setMission(String mission) { this.mission = mission; }

    public String getVision() { return vision; }
    public void setVision(String vision) { this.vision = vision; }

    public String getApproach() { return approach; }
    public void setApproach(String approach) { this.approach = approach; }

    public String getJourney() { return journey; }
    public void setJourney(String journey) { this.journey = journey; }
}
